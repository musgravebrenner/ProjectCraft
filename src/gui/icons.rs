//! The SVG icons in assets/icons (drawn by tools/make_icons.sh), built into the program, and
//! which command each one belongs to.

use egui::ImageSource;

macro_rules! icons {
    ($($name:literal),* $(,)?) => {
        pub fn icon(name: &str) -> Option<ImageSource<'static>> {
            match name {
                $($name => Some(egui::include_image!(concat!("../../assets/icons/", $name, ".svg"))),)*
                _ => None,
            }
        }
    };
}

